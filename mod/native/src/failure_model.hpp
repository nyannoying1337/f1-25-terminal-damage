#pragma once
// Era-accurate random failures for Grand Prix sessions (gp_failures "realistic"). Pure model, no game access.
// Numbers: race results 2012-2022 from the Jolpica/Ergast API (re/tools/failure_stats.py), 2023-2026 matched with
// the causes in the race reports (re/failure-statistics-research.md, which also has the warning, nursing and partial
// failure estimates).
#include <algorithm>
#include <cmath>
#include <cstdint>
#include <string_view>

#include "power_loss.hpp"

namespace fm {

// The first six are the game's power unit parts and the seventh its gearbox (trigger_failure index); suspension and
// brakes the addon handles itself.
enum Outcome : int { ice, mguk, mguh, es, tc, ce, gearbox, suspension, brakes, n_outcomes };

inline const char *outcome_name(int o)
{
    static const char *const names[n_outcomes] = {"ICE",     "MGU-K",      "MGU-H",  "ES",  "turbo",
                                                  "control electronics", "gearbox", "suspension", "brakes"};
    return o >= 0 && o < n_outcomes ? names[o] : "?";
}

struct Era {
    const char *name;
    // Share of the era's mechanical retirements per outcome, in per mille (sums to 1000). Engine includes its oil,
    // water, cooling and fuel system failures; gearbox includes hydraulics, clutch and driveline; control
    // electronics the electrics (and the V8 era's alternators). Power unit retirements without a named component
    // are split 50 % ICE, 15 % MGU-H, 10 % each turbo, ES and MGU-K, 5 % control electronics. Wheel (mostly pit stop
    // wheel nuts), bodywork and other causes are left out. Generated by re/tools/failure_stats.py era_shares().
    uint16_t share[n_outcomes];
};

inline constexpr Era eras[] = {
    // 2012-2013: 2.4 l V8 with KERS. No turbo or MGU-H; KERS failures cost lap time but rarely stopped a car.
    {"V8", {300, 0, 0, 0, 0, 140, 280, 200, 80}},
    // 2014-2016: first hybrid power units.
    {"early hybrid", {324, 44, 36, 44, 28, 81, 177, 105, 161}},
    // 2017-2021.
    {"hybrid", {450, 22, 30, 22, 22, 56, 175, 72, 151}},
    // 2022-2025: ground effect cars (2022 Jolpica n=41 plus 2023-25 race reports n=56).
    {"ground effect", {467, 31, 52, 31, 37, 38, 211, 44, 89}},
    // 2026: new power units without MGU-H, 350 kW MGU-K (rounds 1-19, n=53; Honda's battery vibrations, Cadillac's
    // brakes). Power unit retirements split 60 % ICE, 15 % turbo, 10 % each ES and MGU-K, 5 % CE; battery 70 % ES.
    {"2026 rules", {306, 51, 0, 90, 32, 70, 255, 59, 137}},
};

struct Season {
    std::string_view id;
    int era;
    // Mechanical retirements per race start over a full Grand Prix distance (about 305 km), measured from that
    // season's race results (crashes and unexplained retirements left out).
    double race_chance;
};

inline constexpr Season seasons[] = {
    {"2012", 0, 0.071}, {"2013", 0, 0.074}, {"2014", 1, 0.126}, {"2015", 1, 0.107}, {"2016", 1, 0.091},
    {"2017", 2, 0.150}, {"2018", 2, 0.107}, {"2019", 2, 0.067}, {"2020", 2, 0.083}, {"2021", 2, 0.050},
    {"2022", 3, 0.093}, {"2023", 3, 0.055}, {"2024", 3, 0.038}, {"2025", 3, 0.029}, {"2026", 4, 0.129},
};
inline constexpr int n_seasons = int(sizeof seasons / sizeof seasons[0]);

inline const Season &season_of(std::string_view id)
{
    for (const Season &s : seasons)
        if (s.id == id)
            return s;
    return seasons[n_seasons - 1];
}
inline const Era &era_of(const Season &s) { return eras[s.era]; }

// A full Grand Prix takes about 90 minutes of driving. Failures spread close to evenly over the distance
// (2012-2022: 9 % in the first tenth, 22 % up to a third, 32 % in the middle third, 37 % in the last third), so a
// constant chance per minute of driving fits; a shorter race distance then gets a proportionally smaller chance.
inline constexpr double gp_minutes = 90.0;

// Chance per second of driving on track.
inline double hazard_per_second(const Season &e, double scale = 1.0)
{
    double p = std::fmin(0.95, e.race_chance * scale);
    return -std::log1p(-p) / (gp_minutes * 60.0);
}

// Seconds of driving until the failure for a uniform random number u in (0, 1): exponential with the era's hazard.
inline double seconds_until_failure(const Season &e, double u, double scale = 1.0)
{
    double h = hazard_per_second(e, scale);
    if (h <= 0 || u <= 0)
        return 1e18;
    return -std::log(u) / h;
}

// Pick the failing part for a uniform random number u in [0, 1).
inline int pick_outcome(const Era &e, double u)
{
    int total = 0;
    for (int i = 0; i < n_outcomes; ++i)
        total += e.share[i];
    double x = u * total;
    for (int i = 0; i < n_outcomes; ++i) {
        if (x < e.share[i])
            return i;
        x -= e.share[i];
    }
    return ice;
}

// Warning signs before the failure: the share of failures announced by symptoms (power cuts, temperatures,
// shifting problems), and how many seconds of driving the symptoms last before the part gives up. About 40 % of real
// failures give at least a lap of warning: temperatures and leaks 3-20 laps, brakes 1-5 laps; bearings, turbos,
// electrics and gearboxes mostly fail without one (estimates from race reports, a lap is about 90 s).
struct Warning {
    double chance;
    double min_lead_s, max_lead_s;
};
inline Warning warning_of(int outcome)
{
    switch (outcome) {
    case ice:
        return {0.5, 180, 900};  // water or oil leak, temperatures: 2-10 laps
    case tc:
    case mguh:
        return {0.15, 10, 60};   // turbo: mostly sudden
    case mguk:
    case es:
        return {0.4, 60, 600};   // derating, battery temperature
    case gearbox:
        // Slow or rough shifts, a gear lost first: Magnussen Imola 2020 (slow upshifts from the start, retired lap 47),
        // Grosjean China 2014 (told to avoid 4th, then lost all gears), Trulli 2010 (lost 2nd, then the rest). The
        // addon plays these as a gearbox decline (gearbox_decline in terminal_damage_probe.cpp).
        return {0.35, 60, 600};
    case ce:
        return {0.1, 5, 30};     // electronics: almost always sudden
    case brakes:
        return {0.6, 90, 450};   // brake temperatures: 1-5 laps
    default:
        return {0.0, 0, 0};      // suspension: no warning
    }
}

// Nursing a part (lift and coast, short shifting) slows the wear during the warning phase: it roughly halves the
// progression of temperature and leak faults, so the remaining time stretches up to twice with how little the car
// runs at full throttle. full_throttle_share is the share of the last minute at full throttle (a normal lap is about
// 0.6-0.7).
inline double nursing_factor(double full_throttle_share)
{
    if (full_throttle_share >= 0.55)
        return 1.0;
    double x = (0.55 - full_throttle_share) / 0.25;  // 0.30 or less: fully nursed
    return 1.0 - 0.5 * std::fmin(1.0, std::fmax(0.0, x));
}

// ---- Partial failures: the game's own temporary faults (re/game-failure-scheduler.md section 5) ----
// Types of the 0x34-byte fault records. 0 (engine) and 4 (ERS flag only) have no visible effect, 6 (tyre) is a
// puncture: not used here.
enum FaultType : int {
    f_slow_shift = 1,    // gearbox shifts slowly
    f_missing_gear = 2,  // one gear is gone
    f_gear_jammed = 3,   // stuck in gear
    f_drs = 5,           // DRS does not open
    f_ers_modes = 7,     // ERS deployment modes locked out
    f_ers_glitch = 8,    // ERS software glitch: a forced mode
    f_lean_fuel = 9,     // only the lean fuel mix
    // Not game faults, the addon runs them. Rear brakes: the rear braking changes (brake-by-wire failure from 2014,
    // the rear brake then runs on its backup circuit; a rear brake problem before).
    f_rear_brakes = 10,
    // Engine power over time (power_loss.hpp): the MGU-K gives nothing for the rest of the race, a battery
    // temperature derate on the straights that clears after many laps, a partial misfire fixed after 10-20 laps.
    // The game's own ERS faults (7, 8) showed no effect in the 0.51.110-0.51.113 test runs (top speed unchanged).
    f_mguk_loss = 11,
    f_battery_derate = 12,
    f_misfire = 13,
    n_fault_types = 14
};

inline const char *fault_name(int t)
{
    switch (t) {
    case f_slow_shift: return "slow gear shifts";
    case f_missing_gear: return "missing gear";
    case f_gear_jammed: return "gear jammed";
    case f_drs: return "DRS failure";
    case f_ers_modes: return "ERS modes locked out";
    case f_ers_glitch: return "ERS software glitch";
    case f_lean_fuel: return "engine on lean fuel";
    case f_rear_brakes: return "rear brake failure";
    case f_mguk_loss: return "MGU-K lost";
    case f_battery_derate: return "battery derate";
    case f_misfire: return "misfire";
    default: return "?";
    }
}

// Duration: laps, or seconds when `seconds`; 999 laps = the rest of the race.
struct FaultSpec {
    double min_duration, max_duration;
    bool seconds;
};
inline FaultSpec fault_spec(int t)
{
    switch (t) {
    case f_slow_shift: return {3, 12, false};
    case f_missing_gear: return {999, 999, false};
    case f_gear_jammed: return {8, 30, true};
    case f_drs: return {999, 999, false};
    case f_ers_modes: return {120, 600, true};
    case f_ers_glitch: return {60, 300, true};
    case f_lean_fuel: return {120, 600, true};
    case f_rear_brakes: return {999, 999, false};  // the rest of the race
    case f_mguk_loss: return {999, 999, false};
    case f_battery_derate: return {2400, 3600, true};  // Bahrain 2024: worst laps 4-15, gone by lap 40
    case f_misfire: return {900, 1800, true};          // Canada 2024: fixed after about 15 laps
    default: return {0, 0, false};
    }
}

// About 0.7 cars finish with a lap-time-relevant problem for every mechanical retirement (estimate), so a season's
// partial failure chance is 0.7 times its retirement rate. Mix (estimate): ERS or MGU-K loss 30 %, misfire or derate
// 20 %, lost or stuck gear 15 %, brakes 15 % (the addon's rear brake failure), DRS 10 %, hydraulics (slow shifts)
// 10 %. The ERS share goes mostly to the addon's MGU-K loss (20 %), the game's two ERS faults keep 5 % each for
// their radio; misfire or derate is battery derate 8 %, misfire 7 %, the game's lean fuel 5 %.
constexpr double partial_per_retirement = 0.7;
struct FaultEra {
    uint16_t share[n_fault_types];  // per mille by fault type
};
// Index = Era. The V8 era has no ERS modes and no MGU-K (KERS was a push-to-pass button): misfire 15 %, lean fuel
// 15.8 %, brakes 15 %, the rest scaled by 0.85.
inline constexpr FaultEra fault_eras[] = {
    {{0, 155, 155, 77, 0, 155, 0, 0, 0, 158, 150, 0, 0, 150}},
    {{0, 100, 100, 50, 0, 100, 0, 50, 50, 50, 150, 200, 80, 70}},
    {{0, 100, 100, 50, 0, 100, 0, 50, 50, 50, 150, 200, 80, 70}},
    {{0, 100, 100, 50, 0, 100, 0, 50, 50, 50, 150, 200, 80, 70}},
    {{0, 100, 100, 50, 0, 100, 0, 50, 50, 50, 150, 200, 80, 70}},
};

// The power course of a partial fault (pl::Kind), pl::none for the others.
inline int power_kind_of_fault(int t)
{
    return t == f_mguk_loss ? pl::mguk_loss : t == f_battery_derate ? pl::battery_derate : t == f_misfire ? pl::misfire
                                                                                                       : pl::none;
}

// The warning signs of a failing part as a power course (pl::Kind): a leak or a dropped cylinder for the engine (u
// picks, 60/40), the MGU-K's and the battery's derating, the turbo losing boost, the MGU-H no longer recharging,
// electrical cut-outs. None for the gearbox (its decline), the brakes (their fade) and the suspension.
inline int warning_kind(int outcome, double u)
{
    switch (outcome) {
    case ice: return u < 0.6 ? pl::leak : pl::dead_cylinder;
    case mguk: return pl::mguk_loss;
    case es: return pl::battery_derate;
    case tc: return pl::turbo;
    case mguh: return pl::mguh;
    case ce: return pl::electrical;
    default: return pl::none;
    }
}

// A failing brake (terminal brakes with warning signs) fades: the rear braking lost at the end of the warning,
// growing with the share of it done (Hamilton, Canada 2014: the pedal "went soft and then fell down completely").
constexpr double brake_fade_max = 0.45;
inline double brake_fade(double done) { return brake_fade_max * std::clamp(done, 0.0, 1.0); }

// After an MGU-K loss the rear calipers do the regeneration's share of the braking and run hot: about 1 in 3 cars
// got a weak rear brake about 10 laps later (Hamilton, Canada 2014; Rosberg 2014 and Ricciardo 2018 managed it).
constexpr double mguk_brake_chance = 1.0 / 3.0;
inline double mguk_brake_after(double u) { return 600.0 + 600.0 * std::clamp(u, 0.0, 1.0); }

// Rear brake failure: share of the rear braking lost. Brake-by-wire failures put the rear on its backup circuit:
// the pedal drives the smaller rear calipers directly (re/failure-realism-research.md section 3). Of 11 real cases
// 6 locked or grabbed the rear (all went off or spun at once: Sainz Bahrain 2020, Verstappen Silverstone 2018,
// Mazepin Bahrain 2021), 3 left the rear weak (all continued: Rosberg Austria 2016, Ocon Monaco 2018, Grosjean braked
// "20 metres earlier" in testing 2016). Lock-ups are reported more often, so 60/40: grabbing 1.6-2.1 times the rear
// torque (with 0-25 % spare rear grip at full braking it locks the rear in the first heavy stop), weak 45-70 % less.
// Returns the change: > 0 the share lost, < 0 the share gained. 0.51.112/113 tests felt no change: the addon's
// value never reached the brake step (fixed in 0.51.114, see on_brake_step).
inline double rear_brake_change(double u, double v)
{
    u = std::clamp(u, 0.0, 1.0);
    return v < 0.4 ? 0.45 + 0.25 * u : -(0.60 + 0.50 * u);
}
inline const FaultEra &fault_era_of(const Season &s) { return fault_eras[s.era]; }
inline double fault_race_chance(const Season &s) { return partial_per_retirement * s.race_chance; }

// Slow shifts: how many times the normal shift time (the game's 0.015 s up, 0.030 s down). Real cases: Magnussen,
// Imola 2020: slow upshifts from the start, about half a second a lap (Haas), getting worse until he retired;
// semi-automatic boxes of the 1990s shifted in 30-50 ms against a few ms for a seamless box. Half a second a lap is
// about 6 times the shift time; 15 times (0.23 s per upshift) felt very heavy in the game (test, 0.51.100).
// Mild 60 % (3-6x), moderate 30 % (6-10x), severe 10 % (10-15x). u picks the tier, v the size in it.
struct ShiftSeverity {
    const char *name;
    int scale;
};
inline ShiftSeverity slow_shift_severity(double u, double v)
{
    auto in = [&](int lo, int hi) { return lo + std::min(hi - lo, int(v * (hi - lo + 1))); };
    if (u < 0.6)
        return {"mild", in(3, 6)};
    if (u < 0.9)
        return {"moderate", in(6, 10)};
    return {"severe", in(10, 15)};
}

// A gearbox that fails with warning signs declines in stages over the lead time: from the start, at half and at four
// fifths of it the symptoms get worse, then the gearbox fails. Two ways (half each): hydraulics (slow shifts, mild ->
// moderate -> severe) or a lost gear (one gear gone, then rough shifts, moderate -> severe).
enum DeclinePath : int { decline_hydraulics, decline_lost_gear };
inline int decline_stage(double fraction) { return fraction >= 1.0 ? 3 : fraction >= 0.8 ? 2 : fraction >= 0.5 ? 1 : 0; }
// Shift time scale of a stage (u picks the size inside the tier); 1 = normal shifts.
inline int decline_shift_scale(int path, int stage, double u)
{
    if (stage <= 0)
        return path == decline_hydraulics ? slow_shift_severity(0.0, u).scale : 1;  // mild, or none with a lost gear
    if (stage == 1)
        return slow_shift_severity(0.7, u).scale;  // moderate
    return slow_shift_severity(0.95, u).scale;     // severe
}

inline int pick_fault(const FaultEra &e, double u)
{
    int total = 0;
    for (int i = 0; i < n_fault_types; ++i)
        total += e.share[i];
    double x = u * total;
    for (int i = 0; i < n_fault_types; ++i) {
        if (x < e.share[i])
            return i;
        x -= e.share[i];
    }
    return f_slow_shift;
}

// Fixed-chance modes (10-50 %, 0.51.117): the chance is for the whole race and the failure comes anywhere between 5 %
// and 95 % of its laps. Before, it always came within the first 15 minutes of driving: a 3-lap race rarely got one, a
// full race always early. The point as a lap (0-based) and the share of that lap; lap -1 without a lap count.
struct RacePoint {
    int lap = -1;
    double in_lap = 0;
};
inline RacePoint race_point(double u, int total_laps)
{
    RacePoint r;
    if (total_laps <= 0)
        return r;
    double x = (0.05 + 0.9 * std::clamp(u, 0.0, 1.0)) * total_laps;
    r.lap = std::min(int(x), total_laps - 1);
    r.in_lap = std::clamp(x - r.lap, 0.0, 1.0);
    return r;
}

inline double seconds_until_fault(const Season &s, double u, double scale = 1.0)
{
    double h = -std::log1p(-std::fmin(0.95, fault_race_chance(s) * scale)) / (gp_minutes * 60.0);
    if (h <= 0 || u <= 0)
        return 1e18;
    return -std::log(u) / h;
}

// Table consistency, checked at compile time: every era's shares add up to 1000 per mille, each era has a fault era,
// and every season names an existing era.
constexpr bool era_tables_consistent()
{
    for (const Era &e : eras) {
        int sum = 0;
        for (int v : e.share)
            sum += v;
        if (sum != 1000)
            return false;
    }
    for (const FaultEra &e : fault_eras) {
        int sum = 0;
        for (int v : e.share)
            sum += v;
        if (sum != 1000)
            return false;
    }
    for (const Season &s : seasons)
        if (s.era < 0 || s.era >= int(sizeof eras / sizeof eras[0]))
            return false;
    return true;
}
static_assert(sizeof eras / sizeof eras[0] == sizeof fault_eras / sizeof fault_eras[0], "one fault era for each era");
static_assert(era_tables_consistent(), "era shares add up to 1000 per mille and every season names an existing era");

}  // namespace fm
